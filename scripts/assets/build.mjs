/**
 * build.mjs — regenerate every registered model from its source, against the
 * footprint the furniture catalogue declares for it.
 *
 * ## The problem
 *
 * The planner reserves a footprint per furniture id (`src/data/furniture.ts`,
 * e.g. `size: [110, 60]` in centimetres). Downloaded assets know nothing about
 * that, so their real dimensions drift from the box the plan drew — measured on
 * the assets this project shipped, the potted plant was a third of its declared
 * size and the coffee table was turned 90 degrees from the axis convention.
 *
 * Patching `scale` and `rotationY` by hand in the model registry hides that for
 * a handful of assets and collapses beyond it. This script derives the numbers
 * instead, from the catalogue, and writes the measured result back so the
 * runtime can fit each model to the footprint of the *instance* it is drawing —
 * which is what makes one plant asset serve `plant`, `plant-tall` and
 * `plant-large`, and makes user-resized furniture scale correctly.
 *
 * ## The two stages
 *
 *   sources/<file>.glb
 *     ├─ normalize.py  (Blender)  orient · centre · seat on floor · fit
 *     └─ optimize.mjs  (glTF)     join · WebP · Draco
 *          └─ public/models/<file>.glb
 *
 * Blender does the part that needs real geometry handling; gltf-transform does
 * the part that needs glTF-native compression. Neither does the other's job.
 *
 * ## Usage
 *
 *   node scripts/assets/build.mjs                 # rebuild all registered models
 *   node scripts/assets/build.mjs plant armchair  # rebuild named files only
 *
 * Sources are read from `assets-src/` (git-ignored, not shipped). A file with no
 * source is skipped with a note rather than failing the run, so the script stays
 * usable when only some sources are present locally.
 */

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { NodeIO, getBounds } from '@gltf-transform/core'
import { ALL_EXTENSIONS } from '@gltf-transform/extensions'
import draco3d from 'draco3dgltf'
import { join } from 'node:path'

const SOURCE_DIR = 'assets-src'
const OUT_DIR = 'public/models'
const REGISTRY = 'src/assets/modelRegistry.ts'
const CATALOGUE = 'src/data/furniture.ts'
const DEVICE_CATALOGUE = 'src/data/devices.ts'

/** Footprints (cm) declared by the catalogues, keyed by id. Later wins, matching
 *  the module's own last-declaration-wins shape. */
function readFootprints() {
  const sizes = new Map()
  for (const file of [CATALOGUE, DEVICE_CATALOGUE]) {
    if (!existsSync(file)) continue
    const src = readFileSync(file, 'utf8')
    const re = /id:\s*'([^']+)'[^}]*?size:\s*\[\s*([\d.]+)\s*,\s*([\d.]+)\s*\]/g
    for (const [, id, w, d] of src.matchAll(re)) sizes.set(id, [Number(w), Number(d)])
  }
  return sizes
}

/** `file` → the ids that use it, from the model registry. */
function readRegistry() {
  const src = readFileSync(REGISTRY, 'utf8')
  const block = src.slice(src.indexOf('export const MODELS'))
  const byFile = new Map()
  const re = /'([^']+)':\s*\{\s*file:\s*'([^']+)'/g
  for (const [, id, file] of block.matchAll(re)) {
    if (!byFile.has(file)) byFile.set(file, [])
    byFile.get(file).push(id)
  }
  return byFile
}

/**
 * Real-world size (metres) of a built GLB.
 *
 * Uses `getBounds` over the scene rather than raw accessor min/max: the
 * normalisation pass writes its fit as a node transform, and the optimiser only
 * bakes that into vertex data when it has a reason to merge meshes. Reading the
 * accessors alone therefore reports the asset's *pre-normalisation* size — which
 * is exactly the number the runtime must not be given.
 */
async function measure(io, path) {
  const doc = await io.read(path)
  const scene = doc.getRoot().getDefaultScene() ?? doc.getRoot().listScenes()[0]
  if (!scene) return null
  const { min, max } = getBounds(scene)
  if (!Number.isFinite(min[0])) return null
  return [max[0] - min[0], max[1] - min[1], max[2] - min[2]].map((n) => Number(n.toFixed(4)))
}

/**
 * Emit the measured sizes as a TypeScript module.
 *
 * Generated rather than fetched: the app is offline-first and the 3D view must
 * not depend on a side-car JSON arriving before it can scale a model correctly.
 * Kept separate from the hand-maintained registry so regenerating assets never
 * rewrites a file a human edits.
 */
function writeModelSizes(built) {
  const rows = built
    .slice()
    .sort((a, b) => (a.file < b.file ? -1 : 1))
    .map((b) => `  '${b.file}': [${b.sizeM.map((n) => n.toFixed(4)).join(', ')}],`)
    .join('\n')

  writeFileSync('src/assets/modelSizes.ts', `/**
 * GENERATED by \`scripts/assets/build.mjs\` — do not edit by hand.
 *
 * Real-world bounding size of each built model, in metres, as \`[x, y, z]\`.
 * The runtime fits a model to the footprint of the *instance* it is drawing, so
 * one asset serves every id and size that reuses it (the three plant ids, or a
 * piece the user resized) without a per-id scale factor in the registry.
 */

export const MODEL_SIZES: Record<string, readonly [number, number, number]> = {
${rows}
}
`)
}

/** Authoritative size from the normalisation pass, if it left a report. */
function readReport(path) {
  if (!existsSync(path)) return null
  try {
    const size = JSON.parse(readFileSync(path, 'utf8')).size
    return Array.isArray(size) && size.length === 3
      ? size.map((n) => Number(n.toFixed(4)))
      : null
  } catch {
    return null
  }
}

async function main() {
  const only = process.argv.slice(2)
  const footprints = readFootprints()
  const registry = readRegistry()
  const io = new NodeIO()
    .registerExtensions(ALL_EXTENSIONS)
    .registerDependencies({
      'draco3d.encoder': await draco3d.createEncoderModule(),
      'draco3d.decoder': await draco3d.createDecoderModule(),
    })

  mkdirSync(OUT_DIR, { recursive: true })
  const staging = '.assets-build'
  mkdirSync(staging, { recursive: true })

  const built = []
  const skipped = []

  for (const [file, ids] of registry) {
    if (only.length > 0 && !only.includes(file)) continue
    // Sources arrive either as a single GLB or, from `fetch.mjs`, as a folder
    // holding a glTF next to its textures.
    const candidates = [
      join(SOURCE_DIR, `${file}.glb`),
      join(SOURCE_DIR, file, `${file}.gltf`),
      join(SOURCE_DIR, `${file}.gltf`),
    ]
    const source = candidates.find((c) => existsSync(c))
    if (!source) {
      skipped.push(file)
      continue
    }

    // The first registered id is the asset's reference footprint. Other ids that
    // reuse the file get fitted at runtime from the measured size below.
    const primary = ids.find((id) => footprints.has(id)) ?? ids[0]
    const [w, d] = footprints.get(primary) ?? [100, 100]

    const normalized = join(staging, `${file}.glb`)
    const reportPath = join(staging, `${file}.json`)
    execFileSync('python3', [
      'scripts/assets/normalize.py', source,
      '--out', normalized,
      '--fit', `${w}x${d}`,
      '--report', reportPath,
    ], { stdio: ['ignore', 'ignore', 'inherit'] })

    execFileSync('node', [
      'scripts/assets/optimize.mjs', normalized, '--out', OUT_DIR,
    ], { stdio: 'inherit' })

    // Blender's own measurement wins. It is taken over every mesh corner in
    // world space by the tool that did the fitting, whereas reading the built
    // glTF back can under-report a multi-part asset — which showed up as an
    // outdoor table set overflowing its footprint at runtime by 6 %.
    const size = readReport(reportPath) ?? await measure(io, join(OUT_DIR, `${file}.glb`))
    built.push({ file, ids, referenceId: primary, footprintCm: [w, d], sizeM: size })
  }

  if (skipped.length > 0) {
    console.log(`\nSkipped (no source in ${SOURCE_DIR}/): ${skipped.join(', ')}`)
  }
  if (built.length > 0) {
    writeModelSizes(built)
    console.log('\nMeasured sizes (m) written to src/assets/modelSizes.ts:')
    for (const b of built) {
      console.log(`  ${b.file.padEnd(16)} ${b.sizeM?.map((n) => n.toFixed(2)).join(' x ')}  (fits ${b.footprintCm.join('x')} cm)`)
    }
  }
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
